def main():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    data_path = os.path.join(base_dir, 'data.json')
    with open(data_path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    matched = 0
    missing_keys = []
    notfound = []  # (key, text not found in question)
    for prob in data:
        for sq in prob['subquestions']:
            key = f"{prob['exam']}:{prob['problemNo']}:{sq['no']}"
            if key not in HINTS:
                missing_keys.append(key)
                continue
            combined = (prob.get('passage', '') + '\n' + sq.get('question', ''))
            cleaned_hints = []
            for h in HINTS[key]:
                t = h['text']
                if t not in combined:
                    notfound.append((key, t[:50]))
                cleaned_hints.append({'text': t, 'reason': h['reason']})
            sq['hints'] = cleaned_hints
            matched += 1

    with open(data_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"Matched {matched} sub-questions with hint data")
    if missing_keys:
        print(f"Missing keys ({len(missing_keys)}):", missing_keys)
    if notfound:
        print(f"Hint text NOT FOUND in question ({len(notfound)}):")
        for k, t in notfound:
            print(f"  {k}  «{t}…»")


if __name__ == '__main__':
    main()
